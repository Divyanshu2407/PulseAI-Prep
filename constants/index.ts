// Feedback schema
export const feedbackSchema = z.object({
    // Five anchored competency ratings are summed by the server for a score out of 25.
    categoryScores: z.array(
        z.object({
            name: z.string(),
            score: z.number().int().min(1).max(5).nullable(),
            assessed: z.boolean(),
            comment: z.string(),
            evidence: z.string(),
        })
    ).length(5),
    strengths: z.array(z.string()),           // Array of strengths
    areasForImprovement: z.array(z.string()), // Array of areas to improve
    finalAssessment: z.string(),             // Summary assessment text
    subjectMastery: z.array(z.object({
        subject: z.string().optional(),
        topic: z.string(),
        fundamentals: z.enum(["Clear", "Developing", "Needs practice", "Not assessed"]),
        application: z.enum(["Clear", "Developing", "Needs practice", "Not assessed"]),
        advanced: z.enum(["Clear", "Developing", "Needs practice", "Not assessed"]),
        evidence: z.string(),
    })).optional(),
});
